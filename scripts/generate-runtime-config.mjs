import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const channel = process.env.SEP_RELEASE_CHANNEL || process.argv[2] || 'beta'
if (!['beta', 'stable'].includes(channel)) throw new Error(`Unsupported release channel: ${channel}`)
const file = resolve(root, `config/release.${channel}.json`)
const release = JSON.parse(await readFile(file, 'utf8'))
if (channel === 'stable' && !(process.env.SEP_BASE_URL || release.sepBaseUrl)) {
  throw new Error('Stable builds require SEP_BASE_URL to be provided explicitly')
}
const value = {
  channel: release.channel,
  environment: process.env.SEP_RELEASE_ENVIRONMENT || release.environment,
  sepBaseUrl: process.env.SEP_BASE_URL || release.sepBaseUrl,
  gatewayUrl: process.env.SEP_GATEWAY_URL || release.gatewayUrl,
  buildTime: new Date().toISOString(),
}
const output = resolve(root, 'electron/common/runtime-config.generated.ts')
const source = `/** Generated by scripts/generate-runtime-config.mjs. Do not edit by hand. */\nexport const generatedRuntimeConfig = ${JSON.stringify(value, null, 2)} as const\n`
await writeFile(output, source)
console.log(`runtime config: ${value.channel}/${value.environment} -> ${value.sepBaseUrl}`)
