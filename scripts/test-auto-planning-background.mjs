/* global window, document, requestAnimationFrame, performance */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import process from 'node:process'
import { log } from 'node:console'
import { chromium } from 'playwright-core'

const origin = process.env.SEP_PREVIEW_ORIGIN ?? 'http://127.0.0.1:5190'
const main = await (await fetch(origin + '/main.tsx')).text()
const html = readFileSync(new URL('./fixtures/auto-planning-background.html', import.meta.url), 'utf8')
  .replace('__REACT__', main.match(/from "([^"]*react\.js[^"]*)"/)[1])
  .replace('__DOM__', main.match(/from "([^"]*react-dom_client[^"]*)"/)[1])
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 850 } })
    page.setDefaultTimeout(7000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/__planning-background', route => route.fulfill({ contentType: 'text/html', body: html }))
    const rows = page.locator('.ent-work-row')
    const openList = async () => { if (await page.getByRole('button', { name: '展开工作列表', exact: true }).isVisible()) await page.getByRole('button', { name: '展开工作列表', exact: true }).click() }
    const closeList = async () => { if (width < 1180 && await page.getByRole('button', { name: '收起工作列表', exact: true }).isVisible()) await page.getByRole('button', { name: '收起工作列表', exact: true }).click() }
    const submit = async goal => {
      await page.getByRole('textbox', { name: '工作目标', exact: true }).fill(goal)
      await page.getByRole('combobox', { name: '模型', exact: true }).selectOption('model')
      await page.getByRole('button', { name: '开始自动编排', exact: true }).click()
    }
    try {
      await page.goto(origin + '/__planning-background')
      await page.evaluate(() => { window.withAttachment = true })
      await submit('设计电商促销方案')
      await page.waitForFunction(() => window.workspace.works.some(work => work.planningDraft?.status === 'planning'))
      await openList()
      assert.equal(await rows.count(), 1)
      await closeList()
      await page.getByRole('button', { name: '首页', exact: true }).click()
      await page.getByText('首页内容', { exact: true }).waitFor()
      await page.evaluate(() => window.emit('arrangement_plan_ready', { planSummary: '促销规划已生成', planSteps: [{ id: 's1', title: '分析促销目标' }] }))
      await page.getByRole('button', { name: '员工', exact: true }).click()
      await page.getByText('员工内容', { exact: true }).waitFor()
      await page.getByRole('button', { name: '工作', exact: true }).click()
      await openList()
      await rows.first().click()
      await closeList()
      await page.getByText('促销规划已生成', { exact: true }).waitFor()
      assert.deepEqual(await page.evaluate(() => [window.counts.plan, window.counts.cancel]), [1, 0])
      await page.getByRole('button', { name: '首页', exact: true }).click()
      await page.evaluate(() => window.complete())
      await page.getByRole('button', { name: '工作', exact: true }).click()
      await openList()
      await rows.first().click()
      await closeList()
      await page.getByRole('button', { name: '确认并开始工作', exact: true }).waitFor({ timeout: 1500 })
      assert.equal(await page.locator('.ent-flowcard.in').count(), 2)
      await page.getByText('促销要求.txt', { exact: true }).first().waitFor()
      await page.screenshot({ path: join(tmpdir(), `sep-planning-restored-${width}.png`), fullPage: true })
      await page.reload()
      await page.getByRole('button', { name: '工作', exact: true }).click()
      await openList()
      await rows.first().click()
      await closeList()
      await page.getByRole('button', { name: '确认并开始工作', exact: true }).waitFor({ timeout: 1500 })
      await page.getByText('促销要求.txt', { exact: true }).first().waitFor()
      await page.getByRole('button', { name: '执行设置', exact: true }).click()
      assert.equal(await page.getByRole('combobox', { name: '模型', exact: true }).inputValue(), 'model')
      assert.equal(await page.evaluate(() => window.workspace.planningController.getRecord(window.lastId).draft.permissions.approvalMode), 'auto-approve')
      await page.getByRole('button', { name: '执行设置', exact: true }).click()
      for (const method of ['updateArrangementExecutionSettings', 'preflightArrangementDraft', 'confirmAndStartArrangement']) {
        await page.evaluate(method => { window.lastConflictRevision = null; window.conflictNext = method }, method)
        await page.getByRole('button', { name: '确认并开始工作', exact: true }).click()
        await page.waitForFunction(() => window.lastConflictRevision && window.workspace.planningController.getRecord(window.lastId)?.draft.revision >= window.lastConflictRevision)
        await page.waitForFunction(() => !document.querySelector('.ent-arr-primary')?.disabled)
        assert.equal(await page.getByRole('dialog').count(), 0, `${method} conflict stays silent`)
        assert.equal(await page.evaluate(() => window.counts.start), 0, 'a conflict must not automatically submit another start')
      }
      await page.evaluate(() => { window.conflictNext = 'updateArrangementExecutionSettings'; window.failReadOnConflict = true })
      await page.getByRole('button', { name: '确认并开始工作', exact: true }).click()
      await page.getByRole('dialog').filter({ hasText: '网络连接失败，请检查网络' }).waitFor()
      await page.getByRole('button', { name: '知道了', exact: true }).click()
      await page.evaluate(() => window.workspace.planningController.load(window.lastId))
      await page.getByRole('button', { name: '确认并开始工作', exact: true }).click()
      await page.locator('.ent-wk').waitFor()
      await openList()
      assert.equal(await rows.count(), 1, 'confirmation keeps one record')
      assert.equal(await page.evaluate(() => window.counts.start), 1)
      await closeList()
      await page.evaluate(() => { window.withAttachment = false })
      await page.evaluate(() => window.workspace.navigate({ name: 'arrange', mode: 'auto' }))
      await submit('制定新品上架计划')
      await page.getByRole('button', { name: '取消编排', exact: true }).waitFor()
      await page.getByRole('button', { name: '取消编排', exact: true }).click()
      await page.getByText('自动编排已取消', { exact: true }).waitFor()
      assert.equal(await page.evaluate(() => window.workspace.works.length), 2)
      await page.evaluate(() => { window.lastConflictRevision = null; window.conflictNext = 'planArrangementDraft' })
      await page.getByRole('button', { name: '重新编排', exact: true }).click()
      await page.waitForFunction(() => window.lastConflictRevision && window.workspace.planningController.getRecord(window.lastId)?.draft.revision >= window.lastConflictRevision)
      assert.equal(await page.getByRole('dialog').count(), 0, 'replanning conflict stays silent')
      await page.getByRole('button', { name: '重新编排', exact: true }).click()
      await page.getByRole('button', { name: '取消编排', exact: true }).waitFor()
      await page.getByRole('button', { name: '首页', exact: true }).click()
      await page.evaluate(() => window.fail())
      await page.getByRole('button', { name: '工作', exact: true }).click()
      await openList()
      await rows.filter({ hasText: '制定新品上架计划' }).click()
      await closeList()
      await page.getByRole('dialog').filter({ hasText: '模型请求超时，请稍后重试' }).waitFor()
      await page.getByRole('button', { name: '知道了', exact: true }).click()
      await page.getByRole('button', { name: '重新编排', exact: true }).click()
      await page.getByRole('button', { name: '取消编排', exact: true }).waitFor()
      const transitionMs = await page.evaluate(async () => { const start = performance.now(); window.workspace.navigate({ name: 'home' }); await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); return performance.now() - start })
      assert.ok(transitionMs < 200, `page switch took ${transitionMs}ms`)
      await page.evaluate(() => { window.workspace.navigate({ name: 'arrange', mode: 'auto' }); window.slowCreate = true })
      await submit('分析电商评价')
      await page.getByRole('button', { name: '首页', exact: true }).click()
      await page.evaluate(() => window.releaseCreate())
      await page.waitForFunction(() => window.workspace.works.length === 3)
      assert.equal(await page.evaluate(() => window.workspace.route.name), 'home', 'late create must not navigate away')
      assert.equal(await page.evaluate(() => window.counts.cancel), 1, 'only explicit cancellation aborts')
      assert.deepEqual(errors, [])
      log(`PASS ${width}px: background planning, reopen, reload, confirmation, cancellation, retry, late submission; switch ${transitionMs.toFixed(1)}ms`)
    } catch (error) {
      log('DIAGNOSTIC', await page.evaluate(() => ({ text: document.body.innerText, counts: window.counts, route: window.workspace?.route })), errors)
      await page.screenshot({ path: join(tmpdir(), `sep-planning-failure-${width}.png`), fullPage: true })
      throw error
    } finally { await page.close() }
  }
} finally { await browser.close() }
